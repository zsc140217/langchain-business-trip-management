def generate_training_data():
    """生成训练数据"""
    training_data = []

    for doc in POLICY_DOCS:
        doc_id = doc["id"]
        doc_content = doc["content"]
        queries = QUERY_TEMPLATES.get(doc_id, [])

        for query in queries:
            training_data.append({
                "query": query,
                "positive": doc_content,
                "doc_id": doc_id,
                "negatives": []  # 稍后添加
            })

    return training_data, POLICY_DOCS

def save_data(training_data, policy_docs, output_dir="learning/embedding_finetune/data_preparation"):
    """保存数据到JSON文件"""
    os.makedirs(output_dir, exist_ok=True)

    # 保存政策文档
    policy_path = os.path.join(output_dir, "policy_docs.json")
    with open(policy_path, 'w', encoding='utf-8') as f:
        json.dump(policy_docs, f, ensure_ascii=False, indent=2)
    print(f"✅ 政策文档已保存: {policy_path}")

    # 保存训练数据
    training_path = os.path.join(output_dir, "training_data_raw.json")
    with open(training_path, 'w', encoding='utf-8') as f:
        json.dump(training_data, f, ensure_ascii=False, indent=2)
    print(f"✅ 训练数据已保存: {training_path}")

    print(f"\n📊 统计:")
    print(f"   - 政策文档: {len(policy_docs)} 个")
    print(f"   - 训练样本: {len(training_data)} 条")

    return policy_path, training_path

